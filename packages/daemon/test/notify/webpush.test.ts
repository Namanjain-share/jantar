import { mkdtemp, readFile, realpath, rm, stat, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import type { Notification } from '../../src/contracts.js';
import { createTestContext, type TestContext } from '../../src/core/testing.js';
import {
  DEFAULT_VAPID_SUBJECT,
  MAX_PAYLOAD_BYTES,
  PUSH_CONCURRENCY,
  VapidError,
  WebPushNotifier,
  createNotifiers,
  encodePayload,
  findWebPush,
  loadOrCreateVapidKeys,
  topicFor,
  type PushSendOptions,
} from '../../src/notify/index.js';
import { TEST_VAPID } from '../api/fakes.js';

let dir: string;
let ctx: TestContext;

beforeEach(async () => {
  dir = await realpath(await mkdtemp(join(await realpath(tmpdir()), 'jantar-e-push-')));
  ctx = createTestContext({ home: join(dir, 'state') });
});
afterEach(async () => {
  await rm(dir, { recursive: true, force: true });
});

const N: Notification = {
  kind: 'question',
  title: 'Question · demo-app · refactor',
  body: 'Which database? — Postgres / SQLite',
  sid: 'sess-aaaa-1111',
  pendingId: 'p1',
  url: '/s/sess-aaaa-1111?card=p1',
  tag: 'sess-aaaa-1111:needs-you',
  ts: '2026-01-15T10:00:00.000Z',
};

function addDevice(id: string) {
  ctx.db.devices.insert({ id, name: id, keyHash: `h-${id}`, scopes: ['read', 'control'], createdAt: N.ts, lastSeenAt: N.ts });
}
function addSub(endpoint: string, deviceId: string, kinds?: Notification['kind'][]) {
  ctx.db.pushSubs.upsert({ subscription: { endpoint, keys: { p256dh: 'p', auth: 'a' } }, deviceId, createdAt: N.ts, ...(kinds ? { kinds } : {}) });
}

describe('VAPID keys', () => {
  it('are created once, 0600 in a 0700 dir, and reused', async () => {
    const file = join(dir, 'state', 'push', 'vapid.json');
    let calls = 0;
    const gen = () => {
      calls += 1;
      return { publicKey: `pub${calls}`, privateKey: `priv${calls}` };
    };
    const a = loadOrCreateVapidKeys(file, { generate: gen, env: {} });
    expect(a).toMatchObject({ publicKey: 'pub1', privateKey: 'priv1', subject: DEFAULT_VAPID_SUBJECT });
    expect((await stat(file)).mode & 0o777).toBe(0o600);
    expect((await stat(join(dir, 'state', 'push'))).mode & 0o777).toBe(0o700);
    const b = loadOrCreateVapidKeys(file, { generate: gen, env: { JANTAR_VAPID_SUBJECT: 'https://example.org/contact' } });
    expect(b).toMatchObject({ publicKey: 'pub1', subject: 'https://example.org/contact' });
    expect(calls).toBe(1);
  });

  it('a real key pair is generated by default', () => {
    const k = loadOrCreateVapidKeys(join(dir, 'v.json'), { env: {} });
    expect(Buffer.from(k.publicKey, 'base64url')).toHaveLength(65);
  });

  it('never replaces a damaged key file (that would silently break every subscription)', async () => {
    const file = join(dir, 'vapid.json');
    await writeFile(file, '{not json');
    expect(() => loadOrCreateVapidKeys(file)).toThrow(VapidError);
    expect(await readFile(file, 'utf8')).toBe('{not json');
    await writeFile(file, '{"publicKey":""}');
    expect(() => loadOrCreateVapidKeys(file)).toThrow(/no VAPID key pair/);
  });
});

describe('WebPushNotifier', () => {
  it('sends the payload to every wanted subscription with VAPID details', async () => {
    const sent: { endpoint: string; payload: string; options: PushSendOptions }[] = [];
    const wp = new WebPushNotifier(ctx, { vapid: TEST_VAPID, sender: async (sub, payload, options) => void sent.push({ endpoint: sub.endpoint, payload, options }) });
    addDevice('d1');
    addDevice('d2');
    addSub('https://fcm.googleapis.com/fcm/send/a', 'd1');
    addSub('https://fcm.googleapis.com/fcm/send/b', 'd2', ['permission']);
    addSub('https://fcm.googleapis.com/fcm/send/c', 'd2', ['question']);

    expect(await wp.send(N)).toEqual({ delivered: 2, failed: 0 });
    expect(sent.map((s) => s.endpoint).sort()).toEqual(['https://fcm.googleapis.com/fcm/send/a', 'https://fcm.googleapis.com/fcm/send/c']);
    const payload = JSON.parse(sent[0]?.payload ?? '{}');
    expect(payload).toEqual({ v: 1, title: N.title, body: N.body, kind: 'question', url: N.url, tag: N.tag, sid: N.sid, pendingId: 'p1', ts: N.ts });
    expect(sent[0]?.options).toMatchObject({
      TTL: 3600,
      urgency: 'high',
      topic: topicFor(N.tag),
      vapidDetails: { subject: TEST_VAPID.subject, publicKey: TEST_VAPID.publicKey, privateKey: TEST_VAPID.privateKey },
    });
    expect(sent[0]?.options.topic).toMatch(/^[A-Za-z0-9_-]{32}$/);

    // Reminders reach subscriptions that want the base kind.
    sent.length = 0;
    await wp.send({ ...N, kind: 'reminder', baseKind: 'permission' } as Notification);
    expect(sent.map((s) => s.endpoint).sort()).toEqual(['https://fcm.googleapis.com/fcm/send/a', 'https://fcm.googleapis.com/fcm/send/b']);
    // Done is "normal" urgency.
    sent.length = 0;
    await wp.send({ ...N, kind: 'done' });
    expect(sent[0]?.options.urgency).toBe('normal');
  });

  it('drops subscriptions that are gone (404/410) or belong to revoked devices; keeps others on errors', async () => {
    const wp = new WebPushNotifier(ctx, {
      vapid: TEST_VAPID,
      sender: async (sub) => {
        if (sub.endpoint.endsWith('/gone')) throw Object.assign(new Error('Gone'), { statusCode: 410 });
        if (sub.endpoint.endsWith('/flaky')) throw Object.assign(new Error('Bad gateway'), { statusCode: 502 });
      },
    });
    addDevice('d1');
    addDevice('d2');
    ctx.db.devices.revoke('d2', N.ts);
    addSub('https://fcm.googleapis.com/fcm/send/ok', 'd1');
    addSub('https://fcm.googleapis.com/fcm/send/gone', 'd1');
    addSub('https://fcm.googleapis.com/fcm/send/flaky', 'd1');
    addSub('https://fcm.googleapis.com/fcm/send/revoked', 'd2');
    addSub('https://fcm.googleapis.com/fcm/send/orphan', 'nobody');
    expect(await wp.send(N)).toEqual({ delivered: 1, failed: 2 });
    expect(ctx.db.pushSubs.list().map((r) => r.subscription.endpoint).sort()).toEqual(['https://fcm.googleapis.com/fcm/send/flaky', 'https://fcm.googleapis.com/fcm/send/ok']);
    const logged = JSON.stringify(ctx.log.records);
    expect(logged).not.toContain('/flaky'); // endpoints are capabilities: only the host is logged
    expect(logged).toContain('fcm.googleapis.com');
  });

  it('never sends to a stored endpoint that is not a known push service, and removes it (SEC-3)', async () => {
    const sent: string[] = [];
    const wp = new WebPushNotifier(ctx, { vapid: TEST_VAPID, sender: async (sub) => void sent.push(sub.endpoint) });
    addDevice('d1');
    // Rows stored before the host check existed.
    addSub('https://10.0.0.1:8443/internal/hook', 'd1');
    addSub('https://169.254.169.254/latest', 'd1');
    addSub('https://mac.tailnet-example.ts.net/x', 'd1');
    addSub('https://web.push.apple.com/ok', 'd1');
    expect(await wp.send(N)).toEqual({ delivered: 1, failed: 0 });
    expect(sent).toEqual(['https://web.push.apple.com/ok']);
    expect(ctx.db.pushSubs.list().map((r) => r.subscription.endpoint)).toEqual(['https://web.push.apple.com/ok']);
  });

  it('sends to at most MAX_PUSH_SUBS_PER_DEVICE subscriptions per device (the newest)', async () => {
    const sent: string[] = [];
    const wp = new WebPushNotifier(ctx, { vapid: TEST_VAPID, sender: async (sub) => void sent.push(sub.endpoint) });
    addDevice('d1');
    addDevice('d2');
    for (let i = 0; i < 9; i++) {
      ctx.db.pushSubs.upsert({
        subscription: { endpoint: `https://fcm.googleapis.com/fcm/send/old${i}`, keys: { p256dh: 'p', auth: 'a' } },
        deviceId: 'd1',
        createdAt: new Date(Date.parse(N.ts) + i * 1000).toISOString(),
      });
    }
    addSub('https://web.push.apple.com/d2', 'd2');
    expect(await wp.send(N)).toEqual({ delivered: 6, failed: 0 });
    expect(sent.filter((e) => e.includes('/old')).sort()).toEqual([4, 5, 6, 7, 8].map((i) => `https://fcm.googleapis.com/fcm/send/old${i}`));
    expect(sent).toContain('https://web.push.apple.com/d2');
  });

  it('runs at most PUSH_CONCURRENCY sends at once, and every one still goes out', async () => {
    let inFlight = 0;
    let peak = 0;
    const done: string[] = [];
    const wp = new WebPushNotifier(ctx, {
      vapid: TEST_VAPID,
      sender: async (sub) => {
        inFlight += 1;
        peak = Math.max(peak, inFlight);
        await new Promise((r) => setTimeout(r, 2));
        inFlight -= 1;
        if (sub.endpoint.endsWith('/x3')) throw Object.assign(new Error('Bad gateway'), { statusCode: 502 });
        done.push(sub.endpoint);
      },
    });
    for (let d = 0; d < 4; d++) {
      addDevice(`d${d}`);
      for (let i = 0; i < 5; i++) addSub(`https://fcm.googleapis.com/fcm/send/d${d}/x${i}`, `d${d}`);
    }
    expect(await wp.send(N)).toEqual({ delivered: 16, failed: 4 });
    expect(peak).toBeLessThanOrEqual(PUSH_CONCURRENCY);
    expect(peak).toBeGreaterThan(1);
    expect(done).toHaveLength(16);
  });

  it('keeps payloads under the push size limit', () => {
    const big = encodePayload({ ...N, body: 'x'.repeat(10_000), title: 't'.repeat(500) });
    expect(Buffer.byteLength(big)).toBeLessThanOrEqual(MAX_PAYLOAD_BYTES);
    expect(JSON.parse(big).kind).toBe('question');
  });

  it('disables itself (and reports why) when the key file is damaged', async () => {
    await writeFile(join(dir, 'bad-vapid.json'), 'garbage');
    const c = createTestContext({ paths: { ...ctx.paths, vapidFile: join(dir, 'bad-vapid.json') } });
    let sends = 0;
    const wp = new WebPushNotifier(c, { sender: async () => void (sends += 1) });
    c.db.devices.insert({ id: 'd1', name: 'd', keyHash: 'h', scopes: ['read'], createdAt: N.ts, lastSeenAt: N.ts });
    c.db.pushSubs.upsert({ subscription: { endpoint: 'https://fcm.googleapis.com/fcm/send/1', keys: { p256dh: 'p', auth: 'a' } }, deviceId: 'd1', createdAt: N.ts });
    expect(wp.publicKey()).toBeNull();
    expect(wp.vapidError()).toMatch(/not valid JSON/);
    expect(await wp.send(N)).toEqual({ delivered: 0, failed: 1 });
    expect(sends).toBe(0);
  });

  it('createNotifiers returns the Web Push channel, creating keys under the state dir on first use', async () => {
    const notifiers = createNotifiers(ctx, {});
    expect(notifiers.map((n) => n.channel)).toEqual(['webpush']);
    const wp = findWebPush(notifiers);
    expect(wp?.publicKey()).toMatch(/^[A-Za-z0-9_-]+$/);
    expect((await stat(ctx.paths.vapidFile)).mode & 0o777).toBe(0o600);
  });
});

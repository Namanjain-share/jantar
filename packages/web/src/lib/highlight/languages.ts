/** Markup files say what they are. */
const MARKUP_LABEL = new Map<string, string>([
  ['svg', 'SVG'],
  ['xml', 'XML'],
  ['plist', 'XML'],
  ['vue', 'Vue'],
]);

/** "session.ts" -> "ts"; "" when the name has no extension (a leading dot does not count). */
export function extOf(name: string): string {
  const base = name.slice(name.lastIndexOf('/') + 1);
  const dot = base.lastIndexOf('.');
  return dot > 0 ? base.slice(dot + 1).toLowerCase() : '';
}

/** The grammar for a file: the daemon's hint when we know it, else the name. */
export function languageFor(name: string, hint?: string | null): LanguageId | null {
  if (hint) {
    const byHint = ALIASES.get(hint.toLowerCase());
    if (byHint) return byHint;
  }
  const base = name.slice(name.lastIndexOf('/') + 1).toLowerCase();
  return BY_NAME.get(base) ?? BY_EXT.get(extOf(base)) ?? null;
}

/** "TypeScript", "SVG", ...; null for a file with no known language. */
export function languageLabel(name: string, lang: LanguageId | null): string | null {
  if (!lang) return null;
  if (lang === 'markup') return MARKUP_LABEL.get(extOf(name)) ?? 'HTML';
  return LABEL.get(lang) ?? null;
}
